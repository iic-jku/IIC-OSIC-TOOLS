"""Convert the ASAP7 HSPICE model cards into ngspice, Xyce and VACASK libraries.

ASAP7 ships its FinFET models as HSPICE BSIM-CMG cards (level 72, model
version 107), one file per corner. This script reads them and writes one
library per simulator, each with the sections tt, ff and ss:

* Xyce has BSIM-CMG 107 built in (level 107), so its cards stay as they are.
* ngspice and VACASK load BSIM-CMG 111.2.1 as an OSDI object compiled from
  Verilog-A. That version no longer knows CAPMOD, COREMOD, ETAQM, NSEG and
  VERSION, so these are dropped (CAPMOD, COREMOD and NSEG are at their only
  remaining behavior in the cards, ETAQM is a 107-only quantum-mechanical
  charge-centroid fit).

Every device is wrapped in a subcircuit named like the CDL model
(nmos_rvt, pmos_lvt, ...) with the terminals d g s b and the parameters l,
nfin and w. w is accepted for compatibility with the CDL netlists and
ignored, the drawn width of a FinFET is nfin times the fin pitch.

Usage: asap7_models.py <hspice-model-dir> <libs.tech-dir>
"""

import re
import sys
from pathlib import Path

CORNERS = {"tt": "7nm_TT_160803.pm", "ff": "7nm_FF_160803.pm", "ss": "7nm_SS_160803.pm"}
DEVICES = [f"{t}mos_{vt}" for t in ("n", "p") for vt in ("lvt", "rvt", "slvt", "sram")]
# Parameters BSIM-CMG 111.2.1 does not accept (see module docstring)
DROP_OSDI = {"capmod", "coremod", "etaqm", "nseg", "version"}
DEFAULT_L = "20n"

HEADER = """{c} ASAP7 7 nm FinFET predictive PDK, BSIM-CMG models for {sim}
{c}
{c} Generated by asap7_models.py from the ASAP7 HSPICE model cards
{c} (asap7_pdk_r1p7/models/hspice, BSIM-CMG version 107).
{c} ASAP7 is a predictive PDK for education and research, it is not
{c} manufacturable.
{c}
{c} Copyright 2020 Lawrence T. Clark, Vinay Vashishtha, or Arizona State
{c} University. BSD 3-Clause License, see LICENSE in the PDK root.
{c}
{c} Devices (subcircuits, terminals d g s b):
{c}   nmos_lvt nmos_rvt nmos_slvt nmos_sram
{c}   pmos_lvt pmos_rvt pmos_slvt pmos_sram
{c} Parameters: l (gate length, default {l}), nfin (fins, default 1),
{c}   w (ignored, accepted for CDL compatibility)
{c} Corners (library sections): tt ff ss
"""


def parse_cards(path):
    """Return {model_name: (polarity, [(param, value), ...])} in file order."""
    models = {}
    current = None
    for raw in Path(path).read_text().splitlines():
        line = raw.split("$")[0].rstrip()
        if not line or line.lstrip().startswith("*"):
            continue
        m = re.match(r"\s*\.model\s+(\S+)\s+([np]mos)\b(.*)", line, re.I)
        if m:
            current = m.group(1).lower()
            models[current] = (m.group(2).lower(), [])
            line = "+" + m.group(3)
        if current is None or not line.lstrip().startswith("+"):
            continue
        body = line.lstrip()[1:]
        for key, val in re.findall(r"([A-Za-z_][A-Za-z0-9_]*)\s*=\s*([-+0-9.eE]+)", body):
            models[current][1].append((key.lower(), val))
    missing = [d for d in DEVICES if d not in models]
    if missing:
        sys.exit(f"[ERROR] {path}: no model card for {', '.join(missing)}")
    return models


def wrap(params, prefix, width=4):
    """Format (key, value) pairs as continuation lines."""
    out = []
    for i in range(0, len(params), width):
        out.append(prefix + " ".join(f"{k}={v}" for k, v in params[i:i + width]))
    return out


def osdi_params(pol, params):
    kept = [(k, v) for k, v in params if k not in DROP_OSDI and k != "level"]
    return [("type", "1" if pol == "nmos" else "-1")] + kept


def ngspice_lib(corners):
    out = HEADER.format(c="*", sim="ngspice (OSDI)", l=DEFAULT_L).splitlines()
    out += ["*", "* Needs bsimcmg.osdi loaded, the PDK .spiceinit does that.", ""]
    for corner, models in corners.items():
        out += [f".lib {corner}", ""]
        for dev in DEVICES:
            pol, params = models[dev]
            out.append(f".model {dev}_bsimcmg bsimcmg_va")
            out += wrap(osdi_params(pol, params), "+ ")
            out.append("")
        for dev in DEVICES:
            out += [
                f".subckt {dev} d g s b l={DEFAULT_L} nfin=1 w=0",
                f"N1 d g s b {dev}_bsimcmg l={{l}} nfin={{nfin}}",
                f".ends {dev}",
                "",
            ]
        out += [f".endl {corner}", ""]
    return "\n".join(out)


def xyce_lib(corners):
    out = HEADER.format(c="*", sim="Xyce (built-in BSIM-CMG 107)", l=DEFAULT_L).splitlines()
    out.append("")
    for corner, models in corners.items():
        out += [f".lib {corner}", ""]
        for dev in DEVICES:
            pol, params = models[dev]
            kept = [(k, v) for k, v in params if k != "level"]
            out.append(f".model {dev}_bsimcmg {pol} level=107")
            out += wrap(kept, "+ ")
            out.append("")
        for dev in DEVICES:
            out += [
                f".subckt {dev} d g s b params: l={DEFAULT_L} nfin=1 w=0",
                f"M1 d g s b {dev}_bsimcmg l={{l}} nfin={{nfin}}",
                f".ends {dev}",
                "",
            ]
        out += [f".endl {corner}", ""]
    return "\n".join(out)


def vacask_lib(corners):
    out = HEADER.format(c="//", sim="VACASK (OSDI)", l=DEFAULT_L).splitlines()
    out += [
        "//",
        "// Use: include \"asap7.lib\" section=tt",
        "// bsimcmg.osdi is found through module_path_prefix in .vacaskrc.toml.",
        "",
    ]
    for corner, models in corners.items():
        out += [f"section {corner}", "", "load \"bsimcmg.osdi\"", ""]
        for dev in DEVICES:
            pol, params = models[dev]
            out.append(f"model {dev}_bsimcmg bsimcmg_va (")
            out += wrap(osdi_params(pol, params), "  ")
            out += [")", ""]
        for dev in DEVICES:
            out += [
                f"subckt {dev}(d g s b)",
                f"  parameters l={DEFAULT_L} nfin=1 w=0",
                f"  n1 (d g s b) {dev}_bsimcmg l=l nfin=nfin",
                "ends",
                "",
            ]
        out += ["endsection", ""]
    # VACASK uses SI suffixes like SPICE, but "u" etc. are fine, keep as is
    return "\n".join(out)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src = Path(sys.argv[1])
    dst = Path(sys.argv[2])
    corners = {c: parse_cards(src / f) for c, f in CORNERS.items()}
    for sim, text in (("ngspice", ngspice_lib(corners)), ("xyce", xyce_lib(corners)), ("vacask", vacask_lib(corners))):
        out = dst / sim / "models" / "asap7.lib"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text)
        print(f"[INFO] Wrote {out}")


if __name__ == "__main__":
    main()
